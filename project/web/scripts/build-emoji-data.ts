/**
 * Regenerates lib/emojiData.ts (the emoji the picker offers) from Unicode's official emoji-test.txt.
 *
 *   node --use-system-ca scripts/build-emoji-data.ts [path-or-url]     (default: the latest file on unicode.org)
 *
 * Only fully-qualified emoji are kept, without skin-tone variants and keycaps (those have no art on the CDN the
 * picker draws from). Run it when a new Unicode emoji release comes out, then commit the result.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE = process.argv[2] ?? 'https://unicode.org/Public/emoji/latest/emoji-test.txt';
const OUT = new URL('../lib/emojiData.ts', import.meta.url);
const LINE = /^([0-9A-F ]+?)\s*;\s*([a-z-]+)\s*#\s*(\S+)\s+E[\d.]+\s+(.+)$/;

const text = /^https?:/.test(SOURCE) ? await (await fetch(SOURCE)).text() : readFileSync(SOURCE, 'utf8');
const version = /^# Version: (.+)$/m.exec(text)?.[1] ?? 'unknown';

const groups: { name: string; emojis: [string, string][] }[] = [];
let current: (typeof groups)[number] | null = null;
for (const line of text.split('\n')) {
  const group = /^# group: (.+)$/.exec(line);
  if (group) {
    current = group[1] === 'Component' ? null : { name: group[1], emojis: [] };
    if (current) groups.push(current);
    continue;
  }
  const m = LINE.exec(line);
  if (!m || !current || m[2] !== 'fully-qualified') continue;
  const name = m[4];
  if (/skin tone|^keycap/.test(name)) continue;
  current.emojis.push([m[3], name]);
}

const total = groups.reduce((n, g) => n + g.emojis.length, 0);
const body = groups
  .map((g) => `  {\n    name: ${JSON.stringify(g.name)},\n    emojis: [\n${g.emojis.map(([e, n]) => `      [${JSON.stringify(e)}, ${JSON.stringify(n)}],`).join('\n')}\n    ],\n  },`)
  .join('\n');

writeFileSync(
  OUT,
  `/* Generated by scripts/build-emoji-data.ts from Unicode emoji-test.txt (version ${version}); do not edit by hand. */\n` +
    `export interface EmojiGroup { name: string; emojis: ReadonlyArray<readonly [string, string]> }\n\n` +
    `/** Every emoji the picker offers, in Unicode order, grouped like the system keyboards. */\n` +
    `export const EMOJI_GROUPS: ReadonlyArray<EmojiGroup> = [\n${body}\n];\n`,
);
console.log(`${total} emoji in ${groups.length} groups (Unicode emoji ${version}) -> lib/emojiData.ts`);
